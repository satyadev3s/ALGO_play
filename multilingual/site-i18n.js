    const leadMatch = rawText.match(/^([\p{Extended_Pictographic}\u2190-\u21FF\u2600-\u26BF\u2700-\u27BF•★🌟🚀🤖🚪🎮💡📏🏆🎯🏪🗑️👁️⬇️▶️👩‍🏫👨‍🏫🍕❤️💻🌐.,!?:;\-—–«»"'\s]*)/u);
